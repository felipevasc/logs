/* Native receipt fixtures + real UI: navigation, partial counts, animation ownership and cancellation. */
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { launchBrowser } from './browser.mjs';
import { captureFailure } from './diagnostics.mjs';
const browser = await launchBrowser(), page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
let phase = 'startup';
const progress = async (revision, changes, { completed = 1, findings = 2, current = 'b' } = {}) => page.evaluate(({ revision, changes, completed, findings, current }) => {
  const entry = Tasks.groups().flatMap(group => group.tasks).find(task => task.cmd === 'triage');
  Tasks.progress({ operationId: entry.operationId, phaseId: 'triage-verify', phase: 'Verificando os indícios e suas evidências', completed, total: 45, unit: 'verificações',
    triage: { revision, completed, total: 45, findings, current, items: changes } });
}, { revision, changes, completed, findings, current });
const item = (id, name, state = 'pending', findings = 0) => ({ id, name, state, findings, countsByLevel: [0, 0, findings, 0, 0], applicable: 10, eligible: 8, coverage: 'partial' });
try {
  await mkdir('output/playwright', { recursive: true });
  await page.goto(process.argv[2] || 'http://127.0.0.1:4173');
  await page.waitForFunction(() => WorkspaceContext?.ready && !WorkspaceContext.changing && state.loaded && !state.loadOverlay);
  await page.evaluate(async () => { await Workspace.showPage('compromises'); window.__mockLatency = { triage: 30000 }; });
  await page.locator('[data-calculate-compromises]').click();
  await page.waitForFunction(() => Tasks.groups().some(group => group.tasks.some(task => task.cmd === 'triage')));
  phase = 'partial receipts';
  const items = [item('a', 'Payload <img src=x onerror=alert(1)>', 'completed', 2), item('b', 'Correlação de eventos', 'running'), ...Array.from({ length: 43 }, (_, index) => item(`rule-${index}`, `Verificação ${index + 3}`))];
  await progress(1, items);
  const main = page.locator('[data-compromises-results]');
  assert.match(await main.locator('.cp-totals').innerText(), /1 de 45 verificadas · 44 restantes · 2 indícios/);
  assert.match(await main.locator('.cp-current').innerText(), /Correlação de eventos/);
  assert.equal(await main.locator('.cp-items img').count(), 0);
  assert.equal(await main.locator('.cp-item').count(), 40);
  await main.locator('[data-cp-more]').click(); assert.equal(await main.locator('.cp-item').count(), 45);
  await main.locator('select').selectOption('completed'); assert.equal(await main.locator('.cp-item').count(), 1);
  await main.locator('.cp-item > summary').click();
  assert.match(await main.locator('.cp-item-detail').innerText(), /Cobertura parcial.*8 \/ 10.*Indício: 2/);
  await progress(2, [item('b', 'Correlação de eventos', 'completed', 1)], { completed: 2, findings: 3, current: null });
  assert.equal(await main.locator('select').inputValue(), 'completed');
  assert.equal(await main.locator('.cp-item[open]').count(), 1);
  await page.screenshot({ path: 'output/playwright/compromises-live-progress.png' });
  phase = 'navigate and reopen';
  await page.evaluate(async () => { await Workspace.showPage('explore'); await Workspace.showPage('compromises'); });
  assert.match(await main.locator('.cp-totals').innerText(), /2 de 45 verificadas/);
  assert.equal(await page.evaluate(() => window.__mockRequests.filter(row => row.cmd === "triage" && !row.cacheOnly).length), 1);
  await page.locator('#workbar-tasks').click();
  const dialog = page.locator('.tasks-overlay');
  await page.waitForFunction(() => document.querySelector('.tasks-overlay .waiting-visual')?.dataset.motion === 'running');
  assert.equal(await dialog.locator('.waiting-visual').getAttribute('data-family'), 'verification');
  await dialog.locator('.cp-details > summary').click();
  await dialog.locator('select').selectOption('findings'); assert.equal(await dialog.locator('.cp-item').count(), 2);
  await page.evaluate(() => { window.__oldTaskVisual = document.querySelector('.tasks-overlay .waiting-visual'); });
  phase = 'independent task lifecycle';
  await page.evaluate(() => { __mockLatency.profile_fields = 3000; void api('profile_fields', {}, { silent: true, latest: 'progress-extra' }).catch(() => {}); });
  await page.waitForFunction(() => document.querySelectorAll('.tasks-overlay .waiting-visual').length === 2);
  assert.equal(await page.evaluate(() => __oldTaskVisual === document.querySelector('.tasks-overlay .waiting-visual')), true);
  assert.equal(await dialog.locator('select').inputValue(), 'findings');
  await page.evaluate(() => Tasks.cancelLatest('progress-extra'));
  await page.waitForFunction(() => document.querySelectorAll('.tasks-overlay .waiting-visual').length === 1);
  assert.equal(await page.evaluate(() => __oldTaskVisual === document.querySelector('.tasks-overlay .waiting-visual')), true);
  await page.waitForFunction(() => document.querySelector('.tasks-overlay .waiting-visual')?.dataset.skit);
  await page.screenshot({ path: 'output/playwright/tasks-live-progress.png' });
  await page.keyboard.press('Escape');
  assert.equal(await dialog.count(), 0);
  assert.equal(await page.evaluate(() => __oldTaskVisual.getAnimations({ subtree: true }).length), 0);
  await page.locator('#workbar-tasks').click();
  await page.waitForFunction(() => document.querySelector('.tasks-overlay .waiting-visual')?.dataset.motion === 'running');
  assert.match(await dialog.locator('.cp-totals').innerText(), /2 de 45 verificadas/);
  phase = 'narrow viewport and reduced motion';
  await page.setViewportSize({ width: 480, height: 900 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForFunction(() => document.querySelector('.tasks-overlay .waiting-visual')?.dataset.motion !== 'running');
  assert.equal(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth), true);
  await page.screenshot({ path: 'output/playwright/tasks-live-progress-narrow.png' });
  phase = 'cancel and ignore late receipts';
  await dialog.locator('[data-cancel]').click();
  await page.waitForFunction(() => ['cancelling', 'cancelled'].includes(Security.status().state));
  await page.waitForFunction(() => Security.status().state === 'cancelled');
  assert.equal(await page.evaluate(() => Security.cached()), null);
  assert.equal(await dialog.locator('.waiting-visual').count(), 0);
  await page.evaluate(() => Tasks.progress({ operationId: __mockRequests.find(row => row.cmd === 'triage' && !row.cacheOnly).operationId, triage: { revision: 999, completed: 45, total: 45, findings: 999, items: [] } }));
  assert.equal(await main.locator('.cp-totals').count(), 0);
  assert.deepEqual(errors, []);
  console.log('Live verification counts, partial findings, navigation, animations, reduced motion and cancellation passed.');
} catch (error) { await captureFailure(page, 'test-compromise-progress', error, { phase }); throw error; }
finally { await browser.close(); }
